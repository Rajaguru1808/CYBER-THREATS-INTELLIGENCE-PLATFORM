from datetime import datetime
from flask_login import UserMixin
from app.extensions import db, bcrypt


class User(db.Model, UserMixin):
    """Represents a platform user. Two roles: 'admin' and 'analyst'."""
    __tablename__ = 'users'

    id = db.Column(db.Integer, primary_key=True)
    username = db.Column(db.String(50), unique=True, nullable=False)
    email = db.Column(db.String(120), unique=True, nullable=False)
    password_hash = db.Column(db.String(255), nullable=False)
    full_name = db.Column(db.String(120))
    role = db.Column(db.Enum('admin', 'analyst', name='user_role'), nullable=False, default='analyst')
    is_active_flag = db.Column('is_active', db.Boolean, nullable=False, default=True)
    last_login = db.Column(db.DateTime)
    created_at = db.Column(db.DateTime, default=datetime.utcnow)
    updated_at = db.Column(db.DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    events = db.relationship('ThreatEvent', backref='creator', lazy='dynamic')
    iocs = db.relationship('IOCAttribute', backref='creator', lazy='dynamic')

    # Flask-Login requires an `is_active` property/attribute
    @property
    def is_active(self):
        return self.is_active_flag

    def set_password(self, plain_password):
        self.password_hash = bcrypt.generate_password_hash(plain_password).decode('utf-8')

    def check_password(self, plain_password):
        return bcrypt.check_password_hash(self.password_hash, plain_password)

    def is_admin(self):
        return self.role == 'admin'

    def to_dict(self):
        return {
            'id': self.id,
            'username': self.username,
            'email': self.email,
            'full_name': self.full_name,
            'role': self.role,
            'is_active': self.is_active_flag,
            'last_login': self.last_login.isoformat() if self.last_login else None,
            'created_at': self.created_at.isoformat() if self.created_at else None,
        }

    def __repr__(self):
        return f'<User {self.username} ({self.role})>'
